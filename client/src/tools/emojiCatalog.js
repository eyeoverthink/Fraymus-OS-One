export function weigh(glyph) {
  const points = [...glyph];
  return {
    codePoints: points.length,
    utf16: glyph.length,
    utf8: new TextEncoder().encode(glyph).length,
    hex: points.map((ch) => "U+" + ch.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")).join(" "),
    sequence: points.length > 1
  };
}
